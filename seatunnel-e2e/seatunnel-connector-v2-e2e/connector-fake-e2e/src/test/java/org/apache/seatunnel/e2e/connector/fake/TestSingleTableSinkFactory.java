package org.apache.seatunnel.e2e.connector.fake;

import org.apache.seatunnel.api.configuration.util.OptionRule;
import org.apache.seatunnel.api.table.catalog.CatalogTable;
import org.apache.seatunnel.api.table.connector.TableSink;
import org.apache.seatunnel.api.table.factory.TableSinkFactory;
import org.apache.seatunnel.api.table.factory.TableSinkFactoryContext;
import org.apache.seatunnel.api.table.type.SeaTunnelRow;

/** Top-level SPI factory for {@link TestSingleTableSink}. */
public class TestSingleTableSinkFactory
        implements TableSinkFactory<SeaTunnelRow, Void, Void, Void> {

    public static final String IDENTIFIER = "TestSingleTableSink";

    @Override
    public String factoryIdentifier() {
        return IDENTIFIER;
    }

    @Override
    public OptionRule optionRule() {
        return OptionRule.builder().build();
    }

    @Override
    public TableSink<SeaTunnelRow, Void, Void, Void> createSink(TableSinkFactoryContext context) {
        CatalogTable catalogTable = context == null ? null : context.getCatalogTable();
        return () -> new TestSingleTableSink(catalogTable);
    }
}
