/**
 * A standalone JDK 11 HTTPS fixture for the seven read-only Broker API routes.
 *
 * <p>The separate control endpoint configures synthetic responses and exposes request observations
 * to the test driver. SeaTunnel connects only to the TLS endpoint.
 */
public final class AlpacaBrokerFixture {
    static final String KEY = "fixture-broker-key";
    static final String SECRET = "fixture-broker-secret";
    static final String KEYSTORE_PASSWORD = "temporary-e2e";
    private static final ObjectMapper JSON = new ObjectMapper();
    private static final String AUTHORIZATION =
            "Basic "
                    + Base64.getEncoder()
                            .encodeToString(
                                    (KEY + ":" + SECRET).getBytes(StandardCharsets.US_ASCII));

    private final Object lock = new Object();
    private ObjectNode scenario = JSON.createObjectNode();
    private final ArrayNode calls = JSON.createArrayNode();

    /**
     * Starts the TLS broker and a separate control listener.
     *
     * <p>The PKCS12 file contains a self-signed certificate generated by the owning integration
     * test. The fixture never dials an external endpoint.
     */
    public static void main(String[] args) throws Exception {
        if (Runtime.version().feature() != 11) {
            throw new IllegalStateException("Alpaca Broker fixture uses JDK 11");
        }
        AlpacaBrokerFixture app = new AlpacaBrokerFixture();
        char[] password = KEYSTORE_PASSWORD.toCharArray();
        KeyStore store = KeyStore.getInstance("PKCS12");
        KeyManagerFactory manager =
                KeyManagerFactory.getInstance(KeyManagerFactory.getDefaultAlgorithm());
        try (InputStream in = Files.newInputStream(Path.of(args[0]))) {
            store.load(in, password);
            manager.init(store, password);
        } finally {
            Arrays.fill(password, '\0');
        }
        SSLContext context = SSLContext.getInstance("TLS");
        context.init(manager.getKeyManagers(), null, null);
        HttpsServer broker = HttpsServer.create(new InetSocketAddress(8443), 16);
        broker.setHttpsConfigurator(new HttpsConfigurator(context));
        broker.createContext("/", app::read);
        broker.setExecutor(Executors.newFixedThreadPool(4));
        broker.start();

        HttpServer control = HttpServer.create(new InetSocketAddress(8080), 4);
        control.createContext("/", app::control);
        control.setExecutor(Executors.newFixedThreadPool(2));
        control.start();
    }

    private void control(HttpExchange exchange) throws IOException {
        try {
            switch (exchange.getRequestURI().getPath()) {
                case "/ready":
                    sendJson(exchange, 200, JSON.createObjectNode().put("ready", true));
                    break;
                case "/trace":
                    ArrayNode snapshot;
                    synchronized (lock) {
                        snapshot = calls.deepCopy();
                    }
                    sendJson(exchange, 200, snapshot);
                    break;
                case "/setup":
                    JsonNode input = JSON.readTree(exchange.getRequestBody().readNBytes(2_000_001));
                    if (!"POST".equals(exchange.getRequestMethod())
                            || !(input instanceof ObjectNode)) {
                        sendJson(exchange, 400, JSON.createObjectNode());
                        break;
                    }
                    synchronized (lock) {
                        scenario = (ObjectNode) input;
                        calls.removeAll();
                    }
                    sendJson(exchange, 200, JSON.createObjectNode().put("ready", true));
                    break;
                default:
                    sendJson(exchange, 404, JSON.createObjectNode());
            }
        } finally {
            exchange.close();
        }
    }

    private void read(HttpExchange exchange) throws IOException {
        try {
            String path = exchange.getRequestURI().getPath();
            Map<String, String> params = parameters(exchange.getRequestURI().getRawQuery());
            boolean authenticated =
                    AUTHORIZATION.equals(exchange.getRequestHeaders().getFirst("Authorization"));
            ObjectNode entry =
                    JSON.createObjectNode()
                            .put("path", path)
                            .put("auth", authenticated)
                            .put("host", exchange.getRequestHeaders().getFirst("Host"))
                            .put("monotonic_ms", TimeUnit.NANOSECONDS.toMillis(System.nanoTime()))
                            .put("epoch_ms", System.currentTimeMillis())
                            .put(
                                    "trading_headers",
                                    exchange.getRequestHeaders().containsKey("APCA-API-KEY-ID")
                                            || exchange.getRequestHeaders()
                                                    .containsKey("APCA-API-SECRET-KEY"));
            ObjectNode sentQuery = entry.putObject("query");
            params.forEach(sentQuery::put);
            ObjectNode config;
            int sequence;
            boolean alreadyHeld = false;
            synchronized (lock) {
                config = scenario;
                sequence = calls.size();
                for (JsonNode call : calls) {
                    alreadyHeld |= call.path("held").asBoolean();
                }
                calls.add(entry);
            }

            if (!authenticated) {
                sendJson(
                        exchange,
                        401,
                        JSON.createObjectNode().put("private", "sensitive-broker-error"));
                return;
            }
            if (!"GET".equals(exchange.getRequestMethod())) {
                sendJson(exchange, 405, JSON.createObjectNode());
                return;
            }

            JsonNode step = config.path("steps").path(sequence);
            boolean requestedHold =
                    matches(config, "hold_token", params.get("page_token"))
                            || matches(config, "hold_created_after", params.get("created_after"))
                            || matches(config, "hold_path", path);
            String mode = step.path("mode").asText();
            if ((!alreadyHeld && requestedHold) || "hold".equals(mode) || "trickle".equals(mode)) {
                block(exchange, entry, "trickle".equals(mode));
                return;
            }
            if (step.has("status")) {
                step.path("headers")
                        .fields()
                        .forEachRemaining(
                                field ->
                                        exchange.getResponseHeaders()
                                                .set(field.getKey(), field.getValue().asText()));
                if (step.has("rate_reset_seconds")) {
                    long reset =
                            Instant.now().getEpochSecond()
                                    + step.path("rate_reset_seconds").asLong();
                    exchange.getResponseHeaders().set("X-RateLimit-Reset", Long.toString(reset));
                    synchronized (lock) {
                        entry.put("reset_at_ms", reset * 1000L);
                    }
                }
                sendJson(
                        exchange,
                        step.path("status").asInt(),
                        JSON.createObjectNode().put("private", "sensitive-broker-error"));
                return;
            }
            byte[] response =
                    step.has("body")
                            ? step.path("body").asText().getBytes(StandardCharsets.UTF_8)
                            : JSON.writeValueAsBytes(result(config, path, params));
            if ("gzip".equals(mode)) {
                ByteArrayOutputStream compressed = new ByteArrayOutputStream();
                try (GZIPOutputStream gzip = new GZIPOutputStream(compressed)) {
                    gzip.write(response);
                }
                response = compressed.toByteArray();
                exchange.getResponseHeaders().set("Content-Encoding", "gzip");
            }
            send(exchange, 200, response);
        } catch (IllegalArgumentException e) {
            sendJson(
                    exchange,
                    422,
                    JSON.createObjectNode().put("private", "unexpected broker URL or parameter"));
        } finally {
            exchange.close();
        }
    }

    private static boolean matches(JsonNode config, String key, String actual) {
        return actual != null && config.has(key) && actual.equals(config.path(key).asText());
    }

    private void block(HttpExchange exchange, ObjectNode entry, boolean trickle)
            throws IOException {
        long start = System.nanoTime();
        synchronized (lock) {
            entry.put("held", true);
        }
        exchange.sendResponseHeaders(200, 1_000_000);
        try (OutputStream out = exchange.getResponseBody()) {
            if (!trickle) {
                // Send no body before the deadline test's budget. A later probe observes TCP close.
                Thread.sleep(2100L);
            }
            for (int i = 0; i < 2400; i++) {
                out.write(' ');
                out.flush();
                Thread.sleep(50L);
            }
        } catch (IOException expected) {
            synchronized (lock) {
                entry.put(
                        "disconnect_ms", TimeUnit.NANOSECONDS.toMillis(System.nanoTime() - start));
            }
        } catch (InterruptedException e) {
            Thread.currentThread().interrupt();
        }
    }

    private static JsonNode result(JsonNode config, String path, Map<String, String> query) {
        switch (path) {
            case "/v1/accounts":
                requireQuery(query, "created_after", "created_before", "sort");
                if (!"asc".equals(query.get("sort"))) {
                    throw new IllegalArgumentException();
                }
                return accounts(config, query);
            case "/v1/accounts/activities":
                requireQuery(query, "after", "until", "direction", "page_size", "page_token");
                return activities(config, query);
            case "/v1/calendar":
                requireQuery(query, "start", "end", "date_type");
                return byDate(
                        config.path("calendar"),
                        query,
                        "settlement".equals(query.get("date_type")) ? "settlement_date" : "date");
            case "/v1/clock":
                requireQuery(query);
                return config.has("clock")
                        ? config.path("clock")
                        : JSON.createObjectNode()
                                .put("timestamp", "2024-02-29T09:30:10.123456789-05:00")
                                .put("is_open", true)
                                .put("next_open", "2024-03-01T09:30:00-05:00")
                                .put("next_close", "2024-02-29T16:00:00-05:00")
                                .putNull("nullable");
            case "/v1/country-info":
                requireQuery(query);
                return config.has("countries") ? config.path("countries") : countries();
            case "/v1/assets":
                requireQuery(query, "asset_class");
                return config.has("assets") ? config.path("assets") : assets(query);
            default:
                if (path.startsWith("/v1/accounts/") && path.endsWith("/documents")) {
                    requireQuery(query, "start", "end");
                    return byDate(config.path("documents").path(path.split("/")[3]), query, "date");
                }
                throw new IllegalArgumentException();
        }
    }

    private static ArrayNode accounts(JsonNode config, Map<String, String> query) {
        int count = config.path("count").asInt();
        Instant after = optionalTime(query.get("created_after"));
        Instant before = optionalTime(query.get("created_before"));
        ArrayNode records = JSON.createArrayNode();
        for (int i = 1; i <= count && records.size() < 1000; i++) {
            String date;
            if (config.path("same_timestamp").asBoolean()) {
                date = "2020-01-03T00:00:00Z";
            } else if (count >= 1000) {
                date =
                        i < 999
                                ? "2020-01-01T00:00:00Z"
                                : i <= 1001
                                        ? "2020-01-02T00:00:00.123456Z"
                                        : "2020-01-03T00:00:00Z";
            } else {
                date = "2020-01-0" + i + "T00:00:00Z";
            }
            Instant created = optionalTime(date);
            if ((after == null || !created.isBefore(after)) && !created.isAfter(before)) {
                ObjectNode account =
                        records.addObject()
                                .put("id", uuid(i))
                                .put("created_at", date)
                                .put("currency", "USD")
                                .put("last_equity", "123456789012345678901234.0000100");
                account.putObject("details").putNull("optional");
            }
        }
        return records;
    }

    private static ArrayNode activities(JsonNode config, Map<String, String> query) {
        if (!"asc".equals(query.get("direction"))) {
            throw new IllegalArgumentException();
        }
        Instant after = optionalTime(query.get("after"));
        Instant until = optionalTime(query.get("until"));
        String cursor = query.get("page_token");
        List<JsonNode> matching = new ArrayList<>();
        for (JsonNode row : config.path("activity_rows")) {
            Instant time = optionalTime(row.path("created_at").asText());
            if ((after == null || time.isAfter(after)) && time.isBefore(until)) {
                matching.add(row);
            }
        }
        int start = 0;
        if (cursor != null) {
            while (start < matching.size()
                    && !cursor.equals(matching.get(start).path("id").asText())) {
                start++;
            }
            if (start == matching.size()) {
                throw new IllegalArgumentException();
            }
            if (config.path("repeat_cursor").asBoolean()) {
                return JSON.createArrayNode().add(matching.get(start));
            }
            start++;
        }
        int size =
                Math.min(
                        Integer.parseInt(query.get("page_size")),
                        config.path("activity_cap").asInt(100));
        return JSON.createArrayNode()
                .addAll(matching.subList(start, Math.min(start + size, matching.size())));
    }

    private static ArrayNode byDate(JsonNode entries, Map<String, String> query, String field) {
        ArrayNode filtered = JSON.createArrayNode();
        String start = query.getOrDefault("start", "");
        String end = query.get("end");
        for (JsonNode row : entries) {
            String date = row.path(field).asText();
            if (date.compareTo(start) >= 0 && date.compareTo(end) <= 0) {
                filtered.add(row);
            }
        }
        return filtered;
    }

    private static ObjectNode countries() {
        ObjectNode result = JSON.createObjectNode();
        result.putObject("ALA").put("full_name", "Åland Islands").put("crypto_risk_rating", "low");
        result.putObject("USA")
                .put("full_name", "United States")
                .put("securities_risk_rating", "restricted")
                .putNull("unknown_extra")
                .putArray("crypto_supported_states")
                .add("NY")
                .add("CA");
        return result;
    }

    private static ArrayNode assets(Map<String, String> query) {
        ArrayNode result = JSON.createArrayNode();
        result.addObject()
                .put("id", uuid(1))
                .put("class", query.getOrDefault("asset_class", "us_equity"))
                .put("symbol", "ACME")
                .put("price_increment", "0.0000000100")
                .put("name", "München 東京")
                .putNull("description")
                .putArray("attributes")
                .add("overnight_tradable")
                .add("fractional_eh_enabled");
        return result;
    }

    private static Instant optionalTime(String text) {
        return text == null ? null : OffsetDateTime.parse(text).toInstant();
    }

    private static String uuid(int index) {
        return String.format(Locale.ROOT, "02518f15-2069-4120-8da3-%012x", index);
    }

    private static void requireQuery(Map<String, String> query, String... allowed) {
        if (!Set.of(allowed).containsAll(query.keySet())) {
            throw new IllegalArgumentException();
        }
    }

    private static Map<String, String> parameters(String encoded) {
        Map<String, String> query = new LinkedHashMap<>();
        if (encoded != null && !encoded.isEmpty()) {
            for (String item : encoded.split("&", -1)) {
                String[] pair = item.split("=", 2);
                if (pair.length != 2
                        || query.putIfAbsent(
                                        URLDecoder.decode(pair[0], StandardCharsets.UTF_8),
                                        URLDecoder.decode(pair[1], StandardCharsets.UTF_8))
                                != null) {
                    throw new IllegalArgumentException();
                }
            }
        }
        return query;
    }

    private static void sendJson(HttpExchange exchange, int code, JsonNode data)
            throws IOException {
        send(exchange, code, JSON.writeValueAsBytes(data));
    }

    private static void send(HttpExchange exchange, int code, byte[] bytes) throws IOException {
        exchange.getResponseHeaders().set("Content-Type", "application/json");
        exchange.sendResponseHeaders(code, bytes.length);
        try (OutputStream out = exchange.getResponseBody()) {
            out.write(bytes);
        }
    }
}
